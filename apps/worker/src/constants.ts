/**
 * ТЗ §11.2: загруженный файл — потенциально вредоносный ввод. Шаг конвейера
 * не должен висеть дольше 30 с: поток снимается, полёт получает код timeout.
 */
export const PIPELINE_TIMEOUT_S = 30;

/**
 * Лимит старого поколения памяти потока. 4-часовой трек занимает единицы МБ,
 * 512 МБ — запас на патологические файлы; сверх лимита поток умирает,
 * а не тянет за собой процесс.
 */
export const PIPELINE_MEMORY_LIMIT_MB = 512;

/**
 * Периодический подбор незавершённых полётов: страховка на случай, если
 * NOTIFY о загрузке потерялся (обрыв соединения с базой).
 */
export const QUEUE_SWEEP_INTERVAL_S = 30;

/**
 * Как часто убирать просроченные анонимные загрузки (ТЗ §11.2). Срок — сутки,
 * опоздание на час пилоту незаметно, а лишних запросов к базе нет.
 */
export const RETENTION_SWEEP_INTERVAL_S = 3600;

/**
 * Полётов за один запрос уборки: после долгого простоя проход не держит
 * тысячи строк и ключей в памяти разом, а идёт пачками.
 */
export const RETENTION_BATCH_SIZE = 100;

/** Ключ .track в объектном хранилище (ТЗ §5.2 шаг 9). */
export const trackObjectKey = (flightId: string): string => `tracks/${flightId}.track`;
