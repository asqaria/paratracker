/** Сроки жизни токенов и окна входа (задача 2.10, ТЗ §10). */
export const AUTH = {
  /**
   * Access-JWT: не отзывается, поэтому короткий. 15 мин — обычный компромисс
   * OWASP между числом refresh-запросов и окном после выхода или кражи.
   */
  accessTokenTtlS: 15 * 60,
  /** Refresh: 30 дней — пилот летает по выходным и не должен входить каждый раз. */
  refreshTokenTtlS: 30 * 24 * 60 * 60,
  /** Сколько живёт незавершённый вход через Google (state, PKCE, nonce). */
  oauthStateTtlS: 10 * 60,
  /**
   * Повтор только что сменённого refresh-токена в этом окне — соседняя
   * вкладка (cookie общая), а не кража. Больше сетевой задержки с запасом.
   */
  refreshReuseGraceS: 30,
  /** Случайные токены и PKCE verifier: 256 бит (RFC 7636 §7.1 советует ≥ 256). */
  tokenBytes: 32,
} as const;
